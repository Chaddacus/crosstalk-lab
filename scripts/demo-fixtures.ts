/**
 * Generate the public REPLAY fixtures from the MOCK only: criteria v0 and the scripted demo edit (tests/e2e/demo.json),
 * dev split. Never write real Jev responses here; those stay in .cache/ (gitignored).
 *   npm run fixtures
 */
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { createMockBackend, MOCK_MODEL } from "../src/core/jev/mock-lexsim.ts";
import { requestHash } from "../src/core/jev/request-hash.ts";
import { buildRequest, QUESTION_ID } from "../src/core/run/request.ts";
import { criteriaHash, textsFromChoiceCriteria, toChoiceCriteria } from "../src/core/data/criteria.ts";
import type { ReplayFixture } from "../src/core/jev/replay.ts";
import { loadCatalog, loadCriteria, loadDev } from "./_load.ts";

const catalog = loadCatalog();
const dev = loadDev();
const v0 = loadCriteria();
const demo = JSON.parse(readFileSync("tests/e2e/demo.json", "utf8")) as { edits: Record<string, { what?: string; not_for?: string; examples?: string[] }> };
const texts1 = textsFromChoiceCriteria(v0);
for (const [op, t] of Object.entries(demo.edits)) texts1[op] = { ...texts1[op], ...t };
const v1 = toChoiceCriteria(catalog.operations, texts1);

const dir = "fixtures/replay";
mkdirSync(dir, { recursive: true });
for (const f of readdirSync(dir)) if (f.endsWith(".json")) rmSync(`${dir}/${f}`);
const mock = createMockBackend();
const round = (x: number) => Math.round(x * 1e5) / 1e5;

for (const [version, criteria] of [
  ["v0", v0],
  ["v1-demo", v1],
] as const) {
  const hash = await criteriaHash(criteria);
  const fx: ReplayFixture = {
    kind: "crosstalk-replay-fixture",
    generatedBy: "scripts/demo-fixtures.ts (MOCK · lexical stand-in, not Jev)",
    note: "Generated by the deterministic lexical mock. These are not Jev outputs.",
    model: MOCK_MODEL,
    criteriaHash: hash,
    criteriaVersion: version,
    split: "dev",
    questionId: QUESTION_ID,
    options: Object.keys(criteria),
    provenance: { confidence: "derived", inputTokens: "estimated" },
    responses: {},
  };
  for (const item of dev) {
    const req = buildRequest(criteria, item.query, MOCK_MODEL);
    const res = await mock.decide(req);
    const d = res.decisions[QUESTION_ID]!;
    if (d.kind !== "choice") throw new Error("expected choice");
    fx.responses[await requestHash(req)] = { choice: d.chosen, p: d.probs.map(round), confidence: round(d.confidence ?? 0), input_tokens: res.usage.inputTokens };
  }
  const file = `${dir}/${hash.slice(0, 12)}.${version}.dev.json`;
  writeFileSync(file, JSON.stringify(fx) + "\n");
  console.log(`wrote ${file} (${Object.keys(fx.responses).length} responses)`);
}
